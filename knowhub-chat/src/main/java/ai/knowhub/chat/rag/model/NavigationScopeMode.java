package ai.knowhub.chat.rag.model;

/**
 * 导航范围模式枚举 —— 控制检索时的章节范围约束强度。
 *
 * 在 RAG 流水线中的角色
 * 当用户问的是某个特定章节的问题时，检索引擎需要知道应该在多大范围内搜索。
 * 本枚举定义了不同强度的范围约束：
 *   #NONE：无约束，在整个文档中搜索
 *   #SOFT：软约束，优先在指定章节搜索，但也允许搜索其他章节
 *   #HARD_SECTION：硬约束，严格限定在指定章节内搜索
 *   #HARD_ITEM：硬约束，严格限定在指定编号项内搜索
 *   #HARD_PARENT_WITH_SIBLINGS：硬约束，限定在父章节及其兄弟章节内搜索
 * @see ConversationStructureAnchor#scopeMode 结构锚点中引用本枚举
 * @see DocumentNavigationDecision 导航决策中使用范围模式
 */
public enum NavigationScopeMode {

    /**
     * 无范围约束。
     *
     * 不限制检索范围，在整个文档（或所有关联文档）中搜索。
     * 适用于用户问的是文档级别的通用问题。
     */
    NONE,

    /**
     * 软范围约束。
     *
     * 优先在指定章节范围内搜索，但也允许搜索其他相关章节。
     * 当指定章节内的结果不足时，可以扩展到更大范围。
     */
    SOFT,

    /**
     * 硬约束：严格限定在指定章节内。
     *
     * 只在指定章节及其子章节内搜索，不扩展到其他章节。
     * 适用于用户明确问的是某个章节的内容。
     */
    HARD_SECTION,

    /**
     * 硬约束：严格限定在指定编号项内。
     *
     * 只在指定编号项的文本范围内搜索，是最严格的约束。
     * 适用于用户明确问的是某个编号项的具体内容。
     */
    HARD_ITEM,

    /**
     * 硬约束：限定在父章节及其兄弟章节内。
     *
     * 在当前章节的父章节、以及父章节下的所有兄弟章节范围内搜索。
     * 适用于用户想对比同级章节或了解章节间关系的场景。
     */
    HARD_PARENT_WITH_SIBLINGS
}
